#!/usr/bin/env python3
"""Write docs/alerts.md: every alert rule with an example of its Telegram message.

    python3 scripts/alert-catalog.py      (or: make alert-catalog)

Placeholders in summary/description are filled with sample values, so the text reads like a real message.
"""
import glob
import os
import re

import yaml

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SAMPLE = {"instance": "api.example.com", "job": "node", "service": "api", "container": "api-backend",
          "name": "api-backend", "image": "registry.example.com/api:1.4.2", "device": "/dev/sda1",
          "datname": "app_db", "application": "api", "pg_app": "api", "pg_db": "app_db", "queue": "emails",
          "consumergroup": "billing", "topic": "orders", "cluster": "search", "integration": "telegram",
          "reason": "rate_limited", "alertname": "SiteDown", "group": "containers", "route": "/api/users/*",
          "path": "", "relname": "orders", "schemaname": "public"}


def render(text):
    text = re.sub(r"\{\{\s*or \$labels\.(\w+) \$labels\.\w+\s*\}\}", lambda m: SAMPLE.get(m[1], m[1]), text)
    text = re.sub(r"\{\{\s*\$labels\.(\w+)\s*\}\}", lambda m: SAMPLE.get(m[1], m[1]), text)
    text = re.sub(r"\{\{\s*\$value\s*\|\s*humanizePercentage\s*\}\}", "12.5%", text)
    text = re.sub(r"\{\{\s*\$value\s*\|\s*humanizeDuration\s*\}\}", "1d 2h", text)
    text = re.sub(r"\{\{\s*\$value\s*\|\s*humanize1024\s*\}\}", "24Mi", text)
    text = re.sub(r"\{\{\s*\$value[^}]*\}\}", "92", text)
    return text.replace("{{", "").replace("}}", "")


out = []
table = ["| Priority | Category | Alert | Fires |", "|---|---|---|---|"]
count = 0
for rel in ["prometheus/rules/alerts.yml", "prometheus/rules/services.yml"] + sorted(
        os.path.relpath(f, ROOT) for f in glob.glob(os.path.join(ROOT, "vmalert/rules/*.yml"))):
    for g in yaml.safe_load(open(os.path.join(ROOT, rel)))["groups"]:
        rules = [r for r in g["rules"] if "alert" in r]
        if not rules:
            continue
        out += [f"## {g['name']}", f"`{rel}`", ""]
        for r in rules:
            count += 1
            a = r.get("annotations", {})
            labels = r.get("labels", {})
            pr = labels.get("priority", labels.get("severity", "-"))
            cat = labels.get("category", "-")
            badge = {"P1": "🔴 P1", "P2": "🟠 P2", "P3": "🟡 P3", "info": "ℹ️ info"}.get(pr, pr)
            when = f"after {r['for']}" if r.get("for") else "immediately"
            table.append(f"| {badge} | {cat} | [{r['alert']}](#{r['alert'].lower()}) | {when} |")
            out += [f"### {r['alert']}", f"{badge}, {cat}, fires {when}.", "", "```",
                    f"🟥 PROD · {badge} · FIRING", render(a.get("summary", "")) or r["alert"], f"🔔 {r['alert']} · {cat.title()}",
                    "📝 " + render(a.get("description", "")), "🕒 2026-10-26 10:15 +05", "📊 Dashboard · 🔕 Silence"]
            if pr in ("P1", "P2"):
                out.append("📣 @user1 @user2")
            out += ["```", ""]

head = ["# Alert catalog", "",
        "Every alert rule in this stack, with an example of the Telegram message it sends.",
        "Generated by `scripts/alert-catalog.py` from `prometheus/rules/*.yml` (PromQL) and `vmalert/rules/*.yml` (LogsQL), "
        "all evaluated by vmalert.",
        "Priority (label `priority`): **P1** = users affected now: loud, tags TELEGRAM_MENTIONS, repeated every 30m, "
        "ignores the maintenance window; **P2** = degraded or about to break: loud, tags, repeated every 1h; "
        "**P3** = working hours: silent, repeated every 24h; **info** = notice (deploys): silent, once. "
        "Each category goes to its own Telegram topic (label `category`).",
        f"{count} alerts. Rules whose exporter is not running have no data and never fire, so optional ones cost nothing.", ""]
head += table[:2] + sorted(table[2:], key=lambda row: row.split("|")[1:3]) + [""]  # by priority, then category
with open(os.path.join(ROOT, "docs", "alerts.md"), "w") as f:
    f.write("\n".join(head + out) + "\n")
print(f"docs/alerts.md: {count} alerts")
